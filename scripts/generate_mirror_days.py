from __future__ import annotations

import argparse
from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

from astral import LocationInfo
from astral.sun import sun

ZONE = ZoneInfo("Europe/Warsaw")
LOCATION = LocationInfo("Szczecin", "Poland", "Europe/Warsaw", 53.4285, 14.5528)
OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "mirror-days.md"


def daylight(day: date) -> tuple[datetime, datetime, timedelta]:
    events = sun(LOCATION.observer, date=day, tzinfo=ZONE)
    sunrise = events["sunrise"]
    sunset = events["sunset"]
    return sunrise, sunset, sunset - sunrise


def mirror_days(year: int) -> tuple[date, dict[date, date]]:
    start = date(year, 1, 1)
    end = date(year, 12, 31)
    days = [start + timedelta(days=offset) for offset in range((end - start).days + 1)]
    durations = {day: daylight(day)[2] for day in days}
    peak = max(days, key=durations.__getitem__)

    before = [day for day in days if day < peak]
    after = [day for day in days if day > peak]
    matches: dict[date, date] = {peak: peak}

    for requested in before:
        matches[requested] = min(
            after,
            key=lambda candidate: (
                abs(durations[candidate] - durations[requested]),
                abs((candidate - peak).days - (peak - requested).days),
            ),
        )
    for requested in after:
        matches[requested] = min(
            before,
            key=lambda candidate: (
                abs(durations[candidate] - durations[requested]),
                abs((peak - candidate).days - (requested - peak).days),
            ),
        )

    return peak, matches


def format_duration(value: timedelta, *, signed: bool = False) -> str:
    seconds = round(value.total_seconds())
    sign = ""
    if seconds < 0:
        sign, seconds = "−", -seconds
    elif signed and seconds > 0:
        sign = "+"
    hours, remainder = divmod(seconds, 3600)
    minutes, seconds = divmod(remainder, 60)
    return f"{sign}{hours:02d}:{minutes:02d}:{seconds:02d}"


def render(year: int, today: date) -> str:
    peak, matches = mirror_days(year)
    start = date(year, 1, 1)
    end = date(year, 12, 31)
    days = [start + timedelta(days=offset) for offset in range((end - start).days + 1)]

    rows: list[str] = []
    for day in days:
        sunrise, sunset, duration = daylight(day)
        match = matches[day]
        match_sunrise, match_sunset, match_duration = daylight(match)
        marker = " **Today**" if day == today else ""
        rows.append(
            f"| {day:%Y-%m-%d}{marker} | {sunrise:%H:%M}–{sunset:%H:%M} | "
            f"{format_duration(duration)} | **{match:%Y-%m-%d}** | "
            f"{match_sunrise:%H:%M}–{match_sunset:%H:%M} | "
            f"{format_duration(match_duration - duration, signed=True)} |"
        )

    today_note = ""
    if today.year == year:
        mirror = matches[today]
        today_note = (
            '!!! info "Today’s mirror day"\n'
            f"    **{today:%A, %d %B %Y}** mirrors **{mirror:%A, %d %B %Y}** "
            f"in Szczecin.\n\n"
        )

    return (
        "<!-- Generated by scripts/generate_mirror_days.py; do not edit by hand. -->\n"
        "# Mirror Days\n\n"
        f"{today_note}"
        f"This is the complete **{year}** calendar for Szczecin "
        "(53.4285° N, 14.5528° E). A mirror day is the date on the other side "
        "of the year's longest day with the closest daylight duration.\n\n"
        f"The longest day is **{peak:%A, %d %B %Y}**. Times use "
        "Europe/Warsaw local time and the standard Astral sunrise/sunset definition. "
        "The final column is the mirror day's daylight minus the selected day's daylight.\n\n"
        "[Source and CLI](https://github.com/wnowicki/mirror-days)\n\n"
        "| Date | Sun | Daylight | Mirror date | Mirror sun | Difference |\n"
        "|---|---:|---:|---|---:|---:|\n"
        + "\n".join(rows)
        + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the mirror-day calendar page.")
    parser.add_argument("year", type=int, nargs="?")
    args = parser.parse_args()
    today = datetime.now(ZONE).date()
    year = args.year or today.year
    OUTPUT.write_text(render(year, today), encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(OUTPUT.parents[1])} for {year}")


if __name__ == "__main__":
    main()
